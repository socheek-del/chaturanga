/**
 * jg-004: writes src/features/board/glyphs.ts, the outlines of the piece characters in hanja and Hangul, so
 * the board never needs a Korean font.
 *
 * Usage: npm run glyphs -w apps/janggi/web   (needs network; the output is committed)
 *
 * The outlines come from Noto Serif KR Black (SIL Open Font License 1.1, see src/features/board/OFL.txt),
 * fetched as a subset of exactly these characters from Google Fonts. Each glyph is centred in a 100x100 box.
 */
import { writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const PIECES = {
  w: { k: '楚', a: '士', b: '象', n: '馬', r: '車', c: '包', p: '卒' },
  b: { k: '漢', a: '士', b: '象', n: '馬', r: '車', c: '包', p: '兵' },
};
/** The same pieces in Korean script, for players who do not read Chinese characters. */
const HANGUL = {
  w: { k: '초', a: '사', b: '상', n: '마', r: '차', c: '포', p: '졸' },
  b: { k: '한', a: '사', b: '상', n: '마', r: '차', c: '포', p: '병' },
};
const FAMILY = 'Noto+Serif+KR:wght@900';
const GLYPH_SIZE = 58;

const text = [PIECES, HANGUL].flatMap((set) => [...Object.values(set.w), ...Object.values(set.b)]).join('');
// An old user agent makes Google Fonts serve TrueType, which opentype.js reads (it does not read WOFF2).
const css = await (
  await fetch(`https://fonts.googleapis.com/css2?family=${FAMILY}&text=${encodeURIComponent(text)}`, {
    headers: { 'User-Agent': 'Mozilla/4.0' },
  })
).text();
const fontUrl = css.match(/url\((https:[^)]+)\)/)?.[1];
if (!fontUrl) throw new Error(`No font URL in:\n${css}`);
const font = opentype.parse(await (await fetch(fontUrl)).arrayBuffer());

function centred(ch) {
  const box = font.getPath(ch, 0, 0, GLYPH_SIZE).getBoundingBox();
  return font.getPath(ch, 50 - (box.x1 + box.x2) / 2, 50 - (box.y1 + box.y2) / 2, GLYPH_SIZE).toPathData(1);
}

const outlines = (set) =>
  Object.fromEntries(
    Object.entries(set).map(([color, types]) => [
      color,
      Object.fromEntries(Object.entries(types).map(([type, ch]) => [type, { char: ch, d: centred(ch) }])),
    ]),
  );

writeFileSync(
  new URL('../src/features/board/glyphs.ts', import.meta.url),
  `/**
 * Generated by scripts/generate-glyphs.mjs: do not edit. Outlines of Noto Serif KR Black (SIL Open Font
 * License 1.1, see OFL.txt next to this file), each centred in a 100x100 box.
 */
export const PIECE_GLYPHS = ${JSON.stringify(outlines(PIECES), null, 2)} as const;

/** The same pieces in Hangul. */
export const HANGUL_GLYPHS = ${JSON.stringify(outlines(HANGUL), null, 2)} as const;
`,
);
console.log('wrote src/features/board/glyphs.ts');
